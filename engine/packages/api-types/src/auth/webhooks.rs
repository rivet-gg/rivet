use serde::{Deserialize, Serialize};
use utoipa::ToSchema;

#[derive(Clone, Debug, Serialize, Deserialize, ToSchema)]
#[schema(as = AuthWebhookKeyStatus)]
pub struct KeyStatus {
	pub generation: u64,
	pub active_kid: String,
	pub pending_kid: Option<String>,
	pub last_emergency_request_id: Option<String>,
	pub last_emergency_generation: Option<u64>,
}

#[derive(Clone, Debug, Deserialize, Serialize, ToSchema)]
#[serde(deny_unknown_fields)]
#[schema(as = AuthWebhookRotateRequest)]
pub struct RotateRequest {
	pub expected_generation: u64,
}

#[derive(Clone, Debug, Deserialize, Serialize, ToSchema)]
#[serde(deny_unknown_fields)]
#[schema(as = AuthWebhookRevokeRequest)]
pub struct RevokeRequest {
	pub request_id: String,
	pub expected_generation: u64,
	pub kids: Vec<String>,
}

#[derive(Clone, Serialize, Deserialize, ToSchema)]
#[schema(as = AuthWebhookSignResponse)]
pub struct SignResponse {
	/// Canonical decimal Unix seconds, generated by the control plane.
	pub timestamp: String,
	pub kid: String,
	/// Unpadded base64url Ed25519 signature of timestamp + '.' + raw request body.
	pub signature: String,
}

#[derive(Clone, Debug, Serialize, Deserialize, ToSchema)]
#[schema(as = AuthWebhookPublicKey)]
pub struct PublicKey {
	pub kty: String,
	pub crv: String,
	pub kid: String,
	#[serde(rename = "use")]
	pub public_key_use: String,
	pub alg: String,
	pub x: String,
}

#[derive(Clone, Debug, Serialize, Deserialize, ToSchema)]
#[schema(as = AuthWebhookJwks)]
pub struct Jwks {
	pub keys: Vec<PublicKey>,
}

#[derive(Clone, Debug, Serialize, Deserialize, ToSchema)]
#[schema(as = AuthWebhookMetadata)]
pub struct Metadata {
	pub namespace_id: rivet_util::Id,
	pub alg: String,
	pub kid: String,
	pub jwks_url: String,
	pub generation: u64,
}

/// Exact request bytes; this schema must remain binary rather than a JSON integer array.
pub struct WebhookPayload;
impl utoipa::PartialSchema for WebhookPayload {
	fn schema() -> utoipa::openapi::RefOr<utoipa::openapi::schema::Schema> {
		use utoipa::openapi::schema::{KnownFormat, ObjectBuilder, SchemaFormat, Type};
		ObjectBuilder::new()
			.schema_type(Type::String)
			.format(Some(SchemaFormat::KnownFormat(KnownFormat::Binary)))
			.into()
	}
}
impl utoipa::ToSchema for WebhookPayload {}
